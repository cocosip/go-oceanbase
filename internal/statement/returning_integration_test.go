//go:build integration

package statement_test

import (
	"context"
	"database/sql"
	"fmt"
	"testing"
	"time"

	"github.com/cocosip/go-oceanbase"
	"github.com/cocosip/go-oceanbase/internal/integrationtest"
)

func TestOraclePreparedReturning(t *testing.T) {
	const probe = "probe"
	db := integrationtest.OpenProfile(t, integrationtest.Profile{Name: "oracle", Env: "OB_ORACLE_DSN", Mode: oceanbase.ModeOracle})
	ctx := integrationtest.TestContext(t)
	table := fmt.Sprintf("OBGR_%d", time.Now().UnixNano())
	if _, err := db.ExecContext(ctx, "CREATE TABLE "+table+" (ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,V VARCHAR2(10))"); err != nil {
		integrationtest.FailOperation(t, "create identity table", err)
	}
	defer func() {
		cleanup, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		if _, err := db.ExecContext(cleanup, "DROP TABLE "+table); err != nil {
			t.Error(err)
		}
	}()
	for _, tc := range []struct {
		name, query string
		input       bool
		want        string
	}{
		{"insert", "INSERT INTO " + table + " (V) VALUES (?) RETURNING ID,V INTO ?,?", true, probe},
		{"no-input", "INSERT INTO " + table + " (V) VALUES ('literal') RETURNING ID,V INTO ?,?", false, "literal"},
		{"update", "UPDATE " + table + " SET V=? WHERE ID=(SELECT MIN(ID) FROM " + table + ") RETURNING ID,V INTO ?,?", true, probe},
		{"delete", "DELETE FROM " + table + " WHERE V=? AND ID=(SELECT MIN(ID) FROM " + table + ") RETURNING ID,V INTO ?,?", true, probe},
	} {
		t.Run(tc.name, func(t *testing.T) {
			tx, err := db.BeginTx(ctx, nil)
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = tx.Rollback() }()
			if _, err := tx.ExecContext(ctx, "INSERT INTO "+table+" (V) VALUES ('probe')"); err != nil {
				t.Fatal(err)
			}
			stmt, err := tx.PrepareContext(ctx, tc.query)
			if err != nil {
				t.Fatal(err)
			}
			defer func() { _ = stmt.Close() }()
			for i := 0; i < 2; i++ {
				if tc.name == "delete" && i == 1 {
					break
				}
				var id int64
				var value string
				args := []any{sql.Out{Dest: &id}, sql.Out{Dest: &value}}
				if tc.input {
					args = append([]any{probe}, args...)
				}
				result, err := stmt.ExecContext(ctx, args...)
				if err != nil {
					t.Fatal(err)
				}
				if n, err := result.RowsAffected(); err != nil || n != 1 || id <= 0 || value != tc.want {
					t.Fatalf("rows=%d id=%d value=%q error=%v", n, id, value, err)
				}
			}
			if err := stmt.Close(); err != nil {
				t.Fatal(err)
			}
			if err := tx.Rollback(); err != nil {
				t.Fatal(err)
			}
			var count int
			if err := db.QueryRowContext(ctx, "SELECT COUNT(*) FROM "+table).Scan(&count); err != nil || count != 0 {
				t.Fatalf("rollback count=%d error=%v", count, err)
			}
		})
	}
}
