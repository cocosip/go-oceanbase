package main

import (
	"context"
	"database/sql"
	"fmt"

	"github.com/cocosip/go-oceanbase"
)

const (
	identityCase        = "oracle-identity"
	identityColumnsSQL  = "SELECT ID,V FROM %s ORDER BY ID"
	identityCountSQL    = "SELECT COUNT(*) FROM %s"
	identityInsertValue = "INSERT INTO %s (V) VALUES (?)"
	identityInsertKey   = "INSERT INTO %s (ID,V) VALUES (?,?)"
	identityRejected    = 32795
	identityColumnID    = "ID"
)

// runOracleIdentity verifies GENERATED AS IDENTITY columns: the server assigns
// keys for generated inserts, an explicit key is accepted BY DEFAULT without
// advancing the sequence, ALWAYS rejects an explicit key with 32795, and the
// dictionary reports the identity column as auto-increment.
func runOracleIdentity(ctx context.Context, s *scenario) error {
	byDefault, err := s.tableNamed(ctx, "IDENT", "(ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,V VARCHAR2(10))")
	if err != nil {
		return err
	}
	for _, step := range []struct {
		key  any
		text string
	}{
		{nil, "a"},
		{100, "b"},
		{nil, "c"},
	} {
		if err = insertIdentity(ctx, s.db, byDefault, step.key, step.text); err != nil {
			return err
		}
	}
	if err = readIdentity(ctx, s.db, byDefault, []identityRow{{1, "a"}, {2, "c"}, {100, "b"}}); err != nil {
		return err
	}
	if err = checkIdentityMetadata(ctx, s.db, byDefault); err != nil {
		return err
	}
	always, err := s.tableNamed(ctx, "IALWAYS", "(ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,V VARCHAR2(10))")
	if err != nil {
		return err
	}
	if err = insertIdentity(ctx, s.db, always, nil, "x"); err != nil {
		return err
	}
	if _, err = s.db.ExecContext(ctx, fmt.Sprintf(identityInsertKey, always), 5, "y"); !onlyServerErrorCode(err, identityRejected) {
		return checkFailure("GENERATED ALWAYS identity accepted an explicit key")
	}
	if err = readIdentity(ctx, s.db, always, []identityRow{{1, "x"}}); err != nil {
		return err
	}
	var stored int
	if err = s.db.QueryRowContext(ctx, fmt.Sprintf(identityCountSQL, always)).Scan(&stored); err != nil {
		return err
	}
	return expect(stored == 1, "rejected explicit key left a stored row")
}

type identityRow struct {
	id   int64
	text string
}

func insertIdentity(ctx context.Context, db *sql.DB, table string, key any, text string) error {
	if key == nil {
		_, err := db.ExecContext(ctx, fmt.Sprintf(identityInsertValue, table), text)
		return err
	}
	_, err := db.ExecContext(ctx, fmt.Sprintf(identityInsertKey, table), key, text)
	return err
}

func readIdentity(ctx context.Context, db *sql.DB, table string, want []identityRow) (err error) {
	rows, err := db.QueryContext(ctx, fmt.Sprintf(identityColumnsSQL, table))
	if err != nil {
		return err
	}
	defer closeInto(rows, &err)
	for _, expected := range want {
		if !rows.Next() {
			if err = rows.Err(); err != nil {
				return err
			}
			return checkFailure("identity row missing")
		}
		var id int64
		var text string
		if err = rows.Scan(&id, &text); err != nil {
			return err
		}
		if err = expect(id == expected.id && text == expected.text, "identity key or value changed"); err != nil {
			return err
		}
	}
	if rows.Next() {
		return checkFailure("unexpected identity row")
	}
	return rows.Err()
}

func checkIdentityMetadata(ctx context.Context, db *sql.DB, table string) (err error) {
	return withSession(ctx, db, func(c *sql.Conn) error {
		rows, err := oceanbase.Metadata(ctx, c, oceanbase.MetadataFilter{
			Kind:        oceanbase.MetadataColumns,
			NamePattern: exactPattern(table),
		})
		if err != nil {
			return err
		}
		defer closeInto(rows, &err)
		wantAuto := map[string]bool{identityColumnID: true, "V": false}
		count := 0
		for rows.Next() {
			var catalog, schema, gotTable, name, typeName, defaultValue, remarks, owner sql.NullString
			var ordinal, length, precision, scale, nullable, autoIncrement, generated sql.NullInt64
			if err = rows.Scan(&catalog, &schema, &gotTable, &name, &ordinal, &typeName, &length, &precision, &scale,
				&nullable, &defaultValue, &remarks, &owner, &autoIncrement, &generated); err != nil {
				return err
			}
			expected, ok := wantAuto[name.String]
			if !ok {
				return checkFailure("unexpected identity metadata column")
			}
			if err = expect(autoIncrement.Valid == expected && (!expected || autoIncrement.Int64 == 1), "identity auto-increment flag changed"); err != nil {
				return err
			}
			count++
		}
		if err = rows.Err(); err != nil {
			return err
		}
		return expect(count == len(wantAuto), "identity metadata column count changed")
	})
}
