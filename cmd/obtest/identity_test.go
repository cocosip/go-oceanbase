const (
	identityCreateFix       = "CREATE TABLE OBT_OFFLINE_IDENT (ID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,V VARCHAR2(10))"
	identityAlwaysFix       = "CREATE TABLE OBT_OFFLINE_IALWAYS (ID INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,V VARCHAR2(10))"
	identityInsertValFix    = "INSERT INTO OBT_OFFLINE_IDENT (V) VALUES (?)"
	identityInsertKeyFix    = "INSERT INTO OBT_OFFLINE_IDENT (ID,V) VALUES (?,?)"
	identitySelectFix       = "SELECT ID,V FROM OBT_OFFLINE_IDENT ORDER BY ID"
	identityAlwaysInsertFix = "INSERT INTO OBT_OFFLINE_IALWAYS (V) VALUES (?)"
	identityAlwaysKeyFix    = "INSERT INTO OBT_OFFLINE_IALWAYS (ID,V) VALUES (?,?)"
	identityAlwaysSelectFix = "SELECT ID,V FROM OBT_OFFLINE_IALWAYS ORDER BY ID"
	identityAlwaysCountFix  = "SELECT COUNT(*) FROM OBT_OFFLINE_IALWAYS"
)

type identityFixtureCase struct {
	name   string
	failAt int
	mutate func(body *[]fixtureStep)
	wantOK bool
}

func identityFixtureCases() []identityFixtureCase {
	return []identityFixtureCase{
		{name: caseRoundTrip, failAt: -1, wantOK: true},
		{name: "sequence-changed", failAt: 4, mutate: func(body *[]fixtureStep) {
			(*body)[4].values = [][]driver.Value{{int64(1), "a"}, {int64(101), "c"}, {int64(100), "b"}}
		}},
		{name: "explicit-key-lost", failAt: 4, mutate: func(body *[]fixtureStep) {
			(*body)[4].values = [][]driver.Value{{int64(1), "a"}, {int64(2), "c"}}
		}},
		{name: "auto-increment-flag", failAt: 5, mutate: func(body *[]fixtureStep) {
			(*body)[5].rows = newIdentityMetadataRows(nil, nil)
		}},
		{name: "ordinary-flagged", failAt: 5, mutate: func(body *[]fixtureStep) {
			(*body)[5].rows = newIdentityMetadataRows(int64(1), int64(1))
		}},
		{name: "metadata-count", failAt: 5, mutate: func(body *[]fixtureStep) {
			rows := newIdentityMetadataRows(int64(1), nil)
			rows.values = rows.values[:1]
			(*body)[5].rows = rows
		}},
		{name: "always-accepted", failAt: 8, mutate: func(body *[]fixtureStep) {
			(*body)[8].err = nil
		}},
		{name: "rejected-row-stored", failAt: 10, mutate: func(body *[]fixtureStep) {
			(*body)[10].values = [][]driver.Value{{int64(5)}}
		}},
	}
}

func TestOracleIdentityWorkflow(t *testing.T) {
	definition := scenarioDefinition(t, identityCase, oceanbase.ModeOracle)
	for _, tc := range identityFixtureCases() {
		t.Run(tc.name, func(t *testing.T) {
			steps := identitySteps(t, tc)
			s := fixtureScenario(t, steps)
			s.mode = oceanbase.ModeOracle
			result := runScenario(context.Background(), s, definition.run)
			want := statusFail
			if tc.wantOK {
				want = statusPass
			}
			objects := 1
			if tc.failAt < 0 || tc.failAt > 6 {
				objects = 2
			}
			if result.Status != want || len(result.Objects) != objects || len(result.CleanupErrors) != 0 {
				t.Fatalf("oracle identity workflow: %+v; want %s", result, want)
			}
			for _, object := range result.Objects {
				if object.State != fixtureDroppedState {
					t.Fatalf("oracle identity object %s state=%s", object.Name, object.State)
				}
			}
		})
	}
}

func identitySteps(t *testing.T, tc identityFixtureCase) []fixtureStep {
	t.Helper()
	body := []fixtureStep{
		{query: identityCreateFix},
		{query: identityInsertValFix, inspect: identityInspect(t, nil, "a")},
		{query: identityInsertKeyFix, inspect: identityInspect(t, 100, "b")},
		{query: identityInsertValFix, inspect: identityInspect(t, nil, "c")},
		{query: identitySelectFix, values: [][]driver.Value{{int64(1), "a"}, {int64(2), "c"}, {int64(100), "b"}}},
		{query: "", rows: newIdentityMetadataRows(int64(1), nil)},
		{query: identityAlwaysFix},
		{query: identityAlwaysInsertFix, inspect: identityInspect(t, nil, "x")},
		{query: identityAlwaysKeyFix, err: &oceanbase.Error{Code: identityRejected}},
		{query: identityAlwaysSelectFix, values: [][]driver.Value{{int64(1), "x"}}},
		{query: identityAlwaysCountFix, values: [][]driver.Value{{int64(1)}}},
	}
	if tc.mutate != nil {
		tc.mutate(&body)
	}
	if tc.failAt >= 0 {
		body = body[:tc.failAt+1]
	}
	created := 1
	if len(body) > 6 {
		created = 2
	}
	if created == 2 {
		return append(body,
			fixtureStep{query: "DROP TABLE OBT_OFFLINE_IALWAYS"},
			fixtureStep{query: "DROP TABLE OBT_OFFLINE_IDENT"},
		)
	}
	return append(body, fixtureStep{query: "DROP TABLE OBT_OFFLINE_IDENT"})
}

func identityInspect(t *testing.T, key any, text string) func([]driver.NamedValue) {
	t.Helper()
	return func(args []driver.NamedValue) {
		if key != nil {
			if len(args) != 2 || fixtureArgText(args[0].Value) != fixtureArgText(key) || fixtureArgText(args[1].Value) != text {
				t.Error("identity insert bound unexpected key/value")
			}
			return
		}
		if len(args) != 1 || fixtureArgText(args[0].Value) != text {
			t.Error("identity insert bound unexpected value")
		}
	}
}

